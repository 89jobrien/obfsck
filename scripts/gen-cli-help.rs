#!/usr/bin/env rust-script
//! ```cargo
//! [dependencies]
//! anyhow = "1"
//! ```
//!
//! Keep `site/cli.html` honest about what the binaries actually do.
//!
//! The page used to claim its help blocks "cannot drift" while being
//! hand-transcribed. Three blocks had in fact drifted, showing the wrong
//! command's output. This regenerates the section from the real `--help`
//! text, and `--check` fails instead of writing when the page is stale.
//!
//! Prefer an installed binary, then fall back to `cargo run`, so `--check`
//! works in a fresh checkout without paying for `cargo install` first.
//!
//! Usage:
//!   rust-script scripts/gen-cli-help.rs           # rewrite site/cli.html
//!   rust-script scripts/gen-cli-help.rs --check   # fail if stale (CI)
//!
//! Repository root is taken from the working directory; set OBFSCK_REPO_ROOT
//! to override.

use anyhow::{Context, Result, bail};
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

/// `(argv, heading id)` for the canonical entry point and its subcommands.
const CANONICAL: &[(&[&str], &str)] = &[
    (&["obfsck"], "canonical-commands"),
    (&["obfsck", "redact"], "canonical-commands"),
    (&["obfsck", "analyze"], "canonical-commands"),
    (&["obfsck", "scan"], "canonical-commands"),
];

/// `(argv, heading id, replacement)` for the deprecated aliases.
const DEPRECATED: &[(&[&str], &str, &str)] = &[
    (&["redact"], "deprecated-binaries", "obfsck redact"),
    (&["analyzer"], "deprecated-binaries", "obfsck analyze"),
    (&["scan"], "deprecated-binaries", "obfsck scan"),
];

fn repo_root() -> Result<PathBuf> {
    if let Ok(explicit) = std::env::var("OBFSCK_REPO_ROOT") {
        return Ok(PathBuf::from(explicit));
    }
    std::env::current_dir().context("cannot determine the current directory")
}

/// Escape the five characters that matter in HTML text and attributes.
fn escape(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            '\'' => out.push_str("&#x27;"),
            _ => out.push(c),
        }
    }
    out
}

/// Capture `--help` for a command, preferring an installed binary.
fn help_text(root: &Path, argv: &[&str]) -> Result<String> {
    let output = if is_on_path(argv[0]) {
        Command::new(argv[0])
            .args(&argv[1..])
            .arg("--help")
            .output()
    } else {
        Command::new("cargo")
            .args(["run", "--quiet", "--bin", argv[0], "--"])
            .args(&argv[1..])
            .arg("--help")
            .current_dir(root)
            .output()
    }
    .with_context(|| format!("running `--help` for '{}'", argv.join(" ")))?;

    let text = if output.stdout.is_empty() {
        String::from_utf8_lossy(&output.stderr).into_owned()
    } else {
        String::from_utf8_lossy(&output.stdout).into_owned()
    };
    Ok(text.trim_end().to_string())
}

fn is_on_path(bin: &str) -> bool {
    let Ok(path) = std::env::var("PATH") else {
        return false;
    };
    path.split(':')
        .any(|dir| Path::new(dir).join(bin).is_file())
}

fn anchor(label: &str) -> String {
    label.replace(' ', "-")
}

/// Render one captured help block.
fn terminal(label: &str, body: &str) -> String {
    format!(
        "<h3 id=\"{a}\">{l}</h3>\n\
         <div class=\"terminal\">\n  \
         <div class=\"terminal-bar\"><span class=\"label\">{l}</span></div>\n  \
         <pre><span class=\"prompt\">$</span> {body}\n</pre>\n\
         </div>\n",
        a = escape(&anchor(label)),
        l = escape(label),
        body = escape(body),
    )
}

fn build_section(root: &Path) -> Result<String> {
    let mut out = String::new();
    out.push_str("      <section id=\"cli\" class=\"reveal\">\n");
    out.push_str("        <h2>CLI</h2>\n");
    out.push_str(
        "        <p class=\"note\">\n\
         \x20         Every block below is the real <code>--help</code> output, generated by\n\
         \x20         <code>rust-script scripts/gen-cli-help.rs</code>. Re-run it after\n\
         \x20         changing any flag, or use <code>--check</code> in CI to catch a\n\
         \x20         stale page.\n\
         \x20       </p>\n",
    );
    out.push_str("        <h3 id=\"canonical-commands\">Canonical commands</h3>\n");
    out.push_str(
        "        <p>\n\
         \x20         <code>obfsck</code> is the supported entry point. The standalone\n\
         \x20         <code>redact</code>, <code>analyzer</code>, and <code>scan</code>\n\
         \x20         binaries still exist for compatibility but warn on every run.\n\
         \x20       </p>\n",
    );

    for (argv, _) in CANONICAL {
        let label = format!("{} --help", argv.join(" "));
        out.push_str(&terminal(&label, &help_text(root, argv)?));
    }

    out.push_str("        <h3 id=\"deprecated-binaries\">Deprecated binaries</h3>\n");
    out.push_str(
        "        <p>\n\
         \x20         Each of these prints a deprecation warning to stderr and forwards to\n\
         \x20         the canonical subcommand. They are kept so existing pre-commit hooks\n\
         \x20         and CI jobs keep working.\n\
         \x20       </p>\n",
    );
    for (argv, _, replacement) in DEPRECATED {
        let label = format!("{} --help", argv.join(" "));
        out.push_str(&format!(
            "        <p class=\"note\">Deprecated &mdash; use <code>{r}</code>.</p>\n",
            r = escape(replacement)
        ));
        out.push_str(&terminal(&label, &help_text(root, argv)?));
    }

    out.push_str("        <h3 id=\"other-binaries\">Other binaries</h3>\n");
    out.push_str(
        "        <p class=\"note\">\n\
         \x20         <code>obfsck-mcp</code> reads JSON-RPC from stdin and does not use\n\
         \x20         clap, so it has no <code>--help</code>. It supports\n\
         \x20         <code>--version</code>. See the guide for the tool surface.\n\
         \x20       </p>\n",
    );
    let api_label = "api --help";
    out.push_str(&terminal(api_label, &help_text(root, &["api"])?));

    out.push_str("      </section>\n");
    Ok(out)
}

fn main() -> Result<()> {
    let check_only = std::env::args().any(|a| a == "--check");
    let root = repo_root()?;
    let page = root.join("site/cli.html");

    let current = fs::read_to_string(&page)
        .with_context(|| format!("reading {}", page.display()))?;

    let start = current
        .find("      <section id=\"cli\"")
        .context("site/cli.html has no <section id=\"cli\"> to replace")?;
    let end_marker = "      </section>\n";
    let end = current[start..]
        .find(end_marker)
        .map(|i| start + i + end_marker.len())
        .context("site/cli.html has an unterminated <section id=\"cli\">")?;

    let section = build_section(&root)?;
    let updated = format!("{}{}{}", &current[..start], section, &current[end..]);

    if check_only {
        if updated != current {
            println!(
                "site/cli.html is stale; run: rust-script scripts/gen-cli-help.rs"
            );
            bail!("captured help does not match the page");
        }
        println!("site/cli.html matches the built binaries");
        return Ok(());
    }

    if updated == current {
        println!("site/cli.html already up to date");
        return Ok(());
    }
    fs::write(&page, updated).with_context(|| format!("writing {}", page.display()))?;
    println!("rewrote site/cli.html");
    Ok(())
}